const FALLBACK: Omit<SkillArea, "name" | "skills"> = { icon: PenLine, tone: "bg-panel text-ink-2" };

/** The look for an area, including ones the server has that this list does not. */
export function areaLook(name: string): Omit<SkillArea, "name" | "skills"> {
  return SKILL_AREAS.find((area) => area.name === name) ?? FALLBACK;
}

/** A stable id for a listed skill, the same on every load. */
export function skillId(name: string): string {
  return `skill-${name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")}`;
}
